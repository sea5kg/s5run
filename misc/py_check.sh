SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" &>/dev/null && pwd)"

check_ret() {
    if [ $1 -ne 0 ]; then
        echo ""
        echo "!!! FAIL: $2"
        echo "********************************************************************************"
        echo ""
        exit $1
    else
        echo ""
        echo "*** SUCCESS: $2"
        echo "********************************************************************************"
        echo ""
    fi
}

cd $SCRIPT_DIR/..

python3 -m pycodestyle \
    --config=misc/pycodestyle.config \
    pys5rungen
check_ret $? "pycodestyle"

python3 -m pylint --max-line-length=120 \
    pys5rungen
check_ret $? "pylint"
